/**
 * 三份提示词的**内置规则正文**：host 半拼装请求时用它、浏览器半的提示词文本域把它当作"当前生效正文"显示。
 *
 * 放在一个不 import 任何东西的模块里，是为了让两半共用同一份文字：host 半的 `summary.ts` / `admission.ts` /
 * `privacy.ts` 都依赖 `@deepseek-ai/dsh-llm`，浏览器半的产物不能把它们打进客户端，若把正文抄进 `src/client/`
 * 就会有两份会各自漂移的副本。**安全外壳与输出 schema 不在这里**——它们写死在三个 host 模块里，页面改不掉。
 *
 * @module
 */

/**
 * 摘要提示词的内置规则正文；配置为空串时用它。
 *
 * 判据只写在**正文与调用形态上**：没有声明目标时，摘要请求里只有「本次调用」（工具名 + 关键参数，见
 * `summary.ts` 的 `describeCall`）、估算大小、这段规则与工具正文——**没有用户文本**。所以旧版那条"用户明确
 * 要求逐行/逐条/完整查看"是**观察不到**的条件——实测该触发在 31 条受保护案例里 0 次命中
 * （`docs/dsh-reasoning-effort-research.md`）。现在的写法把"谁提出要看细节"换成"这条结果是不是要用原文的对象"，
 * 于是主模型自己要看文件细节时同样成立；"整文件读""同路径曾被摘过"这类形态由前缀里的调用形态提供。
 *
 * 第二条分支保持"否则摘要"：同一份实测里，让模型在 keep 与 summarize 之间挑（模型侧最好的一臂）一致率 49%、
 * 精确率 48%，并不优于一律摘要，所以兜底仍是摘要 + 原结果入口，而不是一律保留。
 */
export const DEFAULT_SUMMARY_RULE = [
  '你会拿到一条工具结果。判断它是不是「接下来要逐字使用或核对的材料」：正文本身就是要用原文的部分时',
  '（要照抄或改写的片段、要逐行逐条检查或比对的清单与文件内容、要照着排查的报错原文），返回 keep；',
  '它只是把一件事的结论说清楚时（统计、状态、检索结果、命令输出摘要），改写成一段更短的说明，',
  '只保留对继续工作有用的部分。',
].join('\n')

